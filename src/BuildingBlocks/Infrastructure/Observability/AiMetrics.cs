using System.Diagnostics.Metrics;

namespace BuildingBlocks.Infrastructure.Observability;

public static class AiMetrics
{
    public const string MeterName = "Ecommerce.Ai";
    public const string Version = "1.0.0";

    public static readonly Meter Meter = new(MeterName, Version);

    // Counter — cumulative token counts
    public static readonly Counter<long> InputTokens = Meter.CreateCounter<long>(
        name: "ai.tokens.input",
        unit: "tokens",
        description: "Number of input tokens sent to the LLM");

    public static readonly Counter<long> OutputTokens = Meter.CreateCounter<long>(
        name: "ai.tokens.output",
        unit: "tokens",
        description: "Number of output tokens generated by the LLM");

    // Histogram — request latency distribution
    public static readonly Histogram<double> RequestDuration = Meter.CreateHistogram<double>(
        name: "ai.request.duration",
        unit: "ms",
        description: "Duration of LLM requests");

    // Counter — request count (for rate calculation)
    public static readonly Counter<long> RequestCount = Meter.CreateCounter<long>(
        name: "ai.request.count",
        unit: "requests",
        description: "Number of LLM requests made");

    // Counter — failures
    public static readonly Counter<long> RequestFailures = Meter.CreateCounter<long>(
        name: "ai.request.failures",
        unit: "failures",
        description: "Number of failed LLM requests");
}